create table public.country_visits (
  user_id uuid not null references public.profiles(id) on delete cascade,
  country_code text not null references public.travel_countries(code),
  created_at timestamptz not null default now(),
  primary key (user_id, country_code)
);
create index country_visits_country_idx on public.country_visits(country_code);
alter table public.country_visits enable row level security;
revoke all on public.country_visits from anon, authenticated;
grant select, insert, delete on public.country_visits to authenticated;
create policy visits_read_own on public.country_visits for select to authenticated using ((select auth.uid()) = user_id);
create policy visits_add_own on public.country_visits for insert to authenticated with check ((select auth.uid()) = user_id);
create policy visits_remove_own on public.country_visits for delete to authenticated using ((select auth.uid()) = user_id);

-- Intentionally public aggregate endpoint: fixed query, no arguments or identities.
-- SECURITY DEFINER is required to count all users while individual rows stay private.
create function public.community_country_visits()
returns table(country_code text, visitor_count bigint)
language sql stable security definer set search_path = '' as $$
  select v.country_code, count(*) from public.country_visits v group by v.country_code;
$$;
revoke all on function public.community_country_visits() from public;
grant execute on function public.community_country_visits() to anon, authenticated;
comment on function public.community_country_visits() is 'Public aggregate counts only; deliberately discloses no user IDs, names, emails, or individual lists.';

